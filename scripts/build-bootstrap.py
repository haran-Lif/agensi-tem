"""Build fresh-install DDL from the reviewed schema evidence and current account RPC.
Not a generic pg_dump converter. Unknown schema features fail rather than being dropped.
"""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
s = json.loads((ROOT/'backups/schema/2026-11-24-public-schema.json').read_text())
def q(v): return '"' + v.replace('"','""') + '"'
def lit(v): return "'" + v.replace("'", "''") + "'"
assert not s['views'] and not s['enum_values']
assert all(t['kind']=='r' for t in s['tables'])
lines = ['''-- Fresh Supabase project only. Do not run on an existing installation.
-- Generated by scripts/build-bootstrap.py; no operating data or credentials.
begin;
set local search_path = public, extensions;
do $guard$
begin
  if to_regclass('auth.users') is null or to_regclass('storage.objects') is null then
    raise exception 'Supabase Auth/Storage schemas are required.';
  end if;
  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relname = any(array[''' + ','.join(lit(t['name']) for t in s['tables']) + '''])) then
    raise exception 'Existing app objects found. Use a new Supabase project; bootstrap will not overwrite.';
  end if;
end;
$guard$;
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
grant usage on schema public to anon, authenticated, service_role;
''']
# Identity sequence is created by its column, other sequences before defaults.
identity_sequences={'Project_id_seq'}
for seq in s['sequences']:
 if seq['sequencename'] in identity_sequences: continue
 lines.append(f"create sequence public.{q(seq['sequencename'])} as {seq['data_type']} increment by {seq['increment_by']} minvalue {seq['min_value']} maxvalue {seq['max_value']} start with {seq['start_value']} cache {seq['cache_size']} {'cycle' if seq['cycle'] else 'no cycle'};")
for t in s['tables']:
 cols=[]
 for c in t['columns']:
  assert not c['generated'], 'Review generated expression before adding it'
  col=f"  {q(c['name'])} {c['type']}"
  if c['identity']: col += ' generated '+('always' if c['identity']=='a' else 'by default')+' as identity'
  elif c['default'] is not None: col+=' default '+c['default']
  if c['not_null']: col+=' not null'
  cols.append(col)
 lines.append(f"create table public.{q(t['name'])} (\n"+',\n'.join(cols)+'\n);')
# PK/unique/check precede foreign keys, independent of alphabetical table order.
for foreign in (False,True):
 for t in s['tables']:
  for c in t['constraints'] or []:
   if c['definition'].startswith('FOREIGN KEY')==foreign:
    lines.append(f"alter table public.{q(t['name'])} add constraint {q(c['name'])} {c['definition']};")
for t in s['tables']:
 constraint_indexes={c['name'] for c in t['constraints'] or [] if c['definition'].startswith(('PRIMARY KEY','UNIQUE'))}
 for idx in t['indexes'] or []:
  name=re.search(r'INDEX (\S+) ON',idx)[1].strip('"')
  if name not in constraint_indexes: lines.append(idx+';')
 for c in t['columns']:
  if c['default'] and c['default'].startswith('nextval('):
   seq=re.search(r"nextval\('([^']+)'",c['default'])[1]
   assert seq in {x['sequencename'] for x in s['sequences']}
   lines.append(f"alter sequence public.{q(seq)} owned by public.{q(t['name'])}.{q(c['name'])};")
order=['current_user_app_role','current_user_employee_id','current_user_is_app_admin','current_user_project_ids','current_user_explicit_project_ids','current_user_can_access_task','current_user_can_edit_task_output','app_save_setting','app_admin_upsert_auth_account','validate_employee_review_entry','guard_public_daily_setting','get_public_daily_status']
assert set(order)=={r['name'] for r in s['routines']}
for name in order:
 if name=='app_admin_upsert_auth_account':
  src=(ROOT/'supabase/007_account_admin_rpc.sql').read_text()
  definition=src[src.index('create or replace function'):src.index('\nrevoke all on function')].strip()
 else: definition=next(r['definition'] for r in s['routines'] if r['name']==name).strip()+';'
 lines.append(definition)
for t in s['tables']:
 for trigger in t['triggers'] or []: lines.append(trigger+';')
 # All legacy tables are protected too; only existing policies receive browser grants.
 lines.append(f"alter table public.{q(t['name'])} enable row level security;")
 lines.append(f"revoke all on public.{q(t['name'])} from public, anon, authenticated;")
 lines.append(f"grant all on public.{q(t['name'])} to service_role;")
for p in s['policies']:
 roles=', '.join(q(r) for r in p['roles'])
 line=f"create policy {q(p['policyname'])} on {q(p['schemaname'])}.{q(p['tablename'])} as {p['permissive']} for {p['cmd']} to {roles}"
 if p['qual']: line+=' using ('+p['qual']+')'
 if p['with_check']: line+=' with check ('+p['with_check']+')'
 lines.append(line+';')
 if p['schemaname']=='public':
  privileges='select, insert, update, delete' if p['cmd']=='ALL' else p['cmd']
  lines.append(f"grant {privileges} on public.{q(p['tablename'])} to {roles};")
for seq in s['sequences']:
 lines.append(f"revoke all on sequence public.{q(seq['sequencename'])} from public, anon, authenticated;")
 lines.append(f"grant all on sequence public.{q(seq['sequencename'])} to service_role;")
lines.append('''-- Restrict only the app routines, not unrelated extension functions.
do $acl$
declare f record;
begin
 for f in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace
 where n.nspname='public' and p.proname = any(array['''+', '.join(lit(n) for n in order)+'''])
 loop
  execute format('revoke all on function %s from public, anon, authenticated', f.signature);
  execute format('grant execute on function %s to authenticated, service_role', f.signature);
 end loop;
end;
$acl$;
grant execute on function public.get_public_daily_status() to anon;
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('work-resource-images','work-resource-images',false,10485760,array['image/jpeg','image/png','image/webp','image/gif']),
       ('employee-review-images','employee-review-images',false,10485760,array['image/jpeg','image/png','image/webp','image/gif']);
notify pgrst, 'reload schema';
commit;
''')
(ROOT/'supabase/bootstrap/001_schema.sql').write_text('\n\n'.join(lines))
print('Generated fresh-install schema: 23 tables, 12 routines, 46 policies.')
